"use client";

import React, { useState, useRef, useEffect, Suspense } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import Link from "next/link";
import { apiFetch } from "@/lib/api";
import { safeNextPath } from "@/lib/authRedirect";
import { useAuth } from "@/context/AuthContext";
import { ShieldCheck, KeyRound, AlertCircle, ArrowLeft, RefreshCw, CheckCircle2 } from "lucide-react";

function MFAChallengeContent() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const emailParam = searchParams.get("email") || "";
  const challengeToken = searchParams.get("challenge_token") || "";
  const nextParam = safeNextPath(searchParams.get("next"));

  const { refreshAuth } = useAuth();
  const [digits, setDigits] = useState<string[]>(["", "", "", "", "", ""]);
  const [recoveryCode, setRecoveryCode] = useState("");
  const [isRecoveryCode, setIsRecoveryCode] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);

  const inputRefs = useRef<(HTMLInputElement | null)[]>([]);

  useEffect(() => {
    if (!isRecoveryCode && inputRefs.current[0]) {
      inputRefs.current[0].focus();
    }
  }, [isRecoveryCode]);

  const handleDigitChange = (index: number, val: string) => {
    const clean = val.replace(/\D/g, "");
    if (!clean) {
      const copy = [...digits];
      copy[index] = "";
      setDigits(copy);
      return;
    }

    if (clean.length > 1) {
      // Pasted multiple digits
      handlePasteDigits(clean);
      return;
    }

    const copy = [...digits];
    copy[index] = clean[0];
    setDigits(copy);

    // Auto advance
    if (index < 5 && clean) {
      inputRefs.current[index + 1]?.focus();
    }
  };

  const handleKeyDown = (index: number, e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "Backspace" && !digits[index] && index > 0) {
      inputRefs.current[index - 1]?.focus();
    }
  };

  const handlePasteDigits = (pasted: string) => {
    const clean = pasted.replace(/\D/g, "").slice(0, 6);
    if (!clean) return;
    const copy = ["", "", "", "", "", ""];
    for (let i = 0; i < clean.length; i++) {
      copy[i] = clean[i];
    }
    setDigits(copy);
    const focusIdx = Math.min(clean.length, 5);
    inputRefs.current[focusIdx]?.focus();
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    const finalCode = isRecoveryCode ? recoveryCode.trim() : digits.join("");
    if (!finalCode) {
      setError(isRecoveryCode ? "Please enter your recovery code." : "Please enter all 6 digits.");
      return;
    }
    if (!isRecoveryCode && finalCode.length < 6) {
      setError("Please enter the complete 6-digit code.");
      return;
    }

    setError(null);
    setIsLoading(true);

    try {
      if (isRecoveryCode) {
        await apiFetch<any>("/api/v1/auth/mfa/recovery/", {
          method: "POST",
          body: JSON.stringify({
            challenge_token: challengeToken || undefined,
            recovery_code: finalCode,
          }),
        });
      } else {
        await apiFetch<any>("/api/v1/auth/mfa/verify/", {
          method: "POST",
          body: JSON.stringify({
            challenge_token: challengeToken || undefined,
            code: finalCode,
          }),
        });
      }

      await refreshAuth();
      router.push(nextParam);
    } catch (err: any) {
      setError(err?.message || "Invalid verification code. Please try again.");
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="min-h-screen flex items-center justify-center bg-ivory-50 px-4 py-12">
      <div className="w-full max-w-md bg-white border border-ivory-300 rounded-2xl shadow-sm p-8 space-y-6">
        <div className="text-center space-y-2">
          <div className="w-12 h-12 rounded-xl bg-forest-900 text-ivory-100 flex items-center justify-center mx-auto shadow-sm">
            <ShieldCheck className="w-6 h-6 text-emerald-400" />
          </div>
          <h1 className="text-xl font-bold text-charcoal-900 tracking-tight">
            Two-Factor Authentication
          </h1>
          <p className="text-xs text-charcoal-500">
            {isRecoveryCode
              ? "Enter one of your 10-character emergency recovery codes."
              : `Enter the 6-digit code generated by Google Authenticator${emailParam ? ` for ${emailParam}` : ""}.`}
          </p>
        </div>

        {error && (
          <div role="alert" className="p-3 rounded-lg bg-rose-50 border border-rose-200 text-xs text-rose-800 flex items-center space-x-2">
            <AlertCircle className="w-4 h-4 flex-shrink-0 text-rose-600" />
            <span>{error}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-6">
          {!isRecoveryCode ? (
            <div>
              <label className="block text-xs font-semibold text-charcoal-700 text-center mb-3">
                6-Digit Security Code
              </label>
              <div
                className="flex items-center justify-center gap-2"
                onPaste={(e) => {
                  e.preventDefault();
                  handlePasteDigits(e.clipboardData.getData("text"));
                }}
              >
                {digits.map((digit, idx) => (
                  <input
                    key={idx}
                    ref={(el) => { inputRefs.current[idx] = el; }}
                    type="text"
                    inputMode="numeric"
                    maxLength={1}
                    value={digit}
                    onChange={(e) => handleDigitChange(idx, e.target.value)}
                    onKeyDown={(e) => handleKeyDown(idx, e)}
                    disabled={isLoading}
                    className="w-11 h-12 text-center text-xl font-mono font-bold border border-ivory-300 rounded-xl bg-ivory-50 text-charcoal-900 focus:bg-white focus:outline-none focus:ring-2 focus:ring-forest-900 transition-all disabled:opacity-50"
                  />
                ))}
              </div>
            </div>
          ) : (
            <div>
              <label className="block text-xs font-semibold text-charcoal-700 mb-1.5">
                Emergency Recovery Code
              </label>
              <input
                type="text"
                required
                autoFocus
                maxLength={32}
                value={recoveryCode}
                onChange={(e) => setRecoveryCode(e.target.value.replace(/\s+/g, ""))}
                placeholder="e.g. ABCD-123456"
                disabled={isLoading}
                className="w-full px-4 py-2.5 text-center text-base font-mono tracking-wider border border-ivory-300 rounded-xl bg-ivory-50 text-charcoal-900 placeholder-charcoal-300 focus:outline-none focus:ring-2 focus:ring-forest-900 disabled:opacity-50"
              />
            </div>
          )}

          <button
            type="submit"
            disabled={isLoading || (!isRecoveryCode && digits.some((d) => !d)) || (isRecoveryCode && !recoveryCode.trim())}
            className="w-full py-2.5 px-4 bg-forest-900 hover:bg-forest-800 text-ivory-100 rounded-xl text-xs font-semibold shadow-sm transition-colors disabled:opacity-50 flex items-center justify-center space-x-2"
          >
            {isLoading ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin" />
                <span>Verifying...</span>
              </>
            ) : (
              <span>Verify &amp; Continue</span>
            )}
          </button>
        </form>

        <div className="pt-2 border-t border-ivory-200 flex flex-col items-center space-y-2 text-xs">
          <button
            type="button"
            onClick={() => {
              setIsRecoveryCode(!isRecoveryCode);
              setDigits(["", "", "", "", "", ""]);
              setRecoveryCode("");
              setError(null);
            }}
            className="text-forest-900 hover:text-forest-800 font-semibold flex items-center space-x-1"
          >
            <KeyRound className="w-3.5 h-3.5" />
            <span>{isRecoveryCode ? "Use Authenticator App (TOTP)" : "Lost device? Use a backup recovery code"}</span>
          </button>

          <Link
            href="/login"
            className="text-charcoal-500 hover:text-charcoal-800 font-medium flex items-center space-x-1"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Back to sign in</span>
          </Link>
        </div>
      </div>
    </div>
  );
}

export default function MFAChallengePage() {
  return (
    <Suspense fallback={<div className="min-h-screen flex items-center justify-center text-xs text-charcoal-400">Loading...</div>}>
      <MFAChallengeContent />
    </Suspense>
  );
}
